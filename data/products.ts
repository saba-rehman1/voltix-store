export const getProduct = (slug: string) =>
  products.find((p) => p.slug === slug);

export const getProductById = (id: string) => products.find((p) => p.id === id);

export const getRelatedProducts = (product: Product, count = 4) =>
  products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, count);

export const brands = Array.from(new Set(products.map((p) => p.brand))).sort();

export const allColors = Array.from(
  new Set(products.flatMap((p) => p.colors?.map((c) => c.name) ?? []))
).sort();

export const allStorage = Array.from(
  new Set(products.flatMap((p) => p.storageOptions ?? []))
).sort();

export const allRam = Array.from(
  new Set(products.flatMap((p) => p.ramOptions ?? []))
).sort();

export const allProcessors = Array.from(
  new Set(products.flatMap((p) => p.processorOptions ?? []))
).sort();

export const allScreenSizes = Array.from(
  new Set(products.map((p) => p.screenSize).filter(Boolean) as string[])
).sort();
