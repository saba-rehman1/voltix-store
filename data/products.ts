function mkReview(
  author: string,
  rating: number,
  date: string,
  title: string,
  body: string,
  helpful = 0,
  verified = true
): Review {
  return {
    id: `rv-${rid++}`,
    author,
    avatar: `https://ui-avatars.com/api/?name=${encodeURIComponent(
      author
    )}&background=161B22&color=B8C0CC&bold=true&size=100`,
    rating,
    date,
    title,
    body,
    verified,
    helpful,
  };
}

